#!/usr/bin/env python3
"""Shared skill version manifest: the list ChatGPT and any new Claude session load, generated from the SKILL.md files themselves.

    python3 tools/qa/skill_manifest.py            write docs/production/SKILL_MANIFEST.json and SKILL_MANIFEST.md
    python3 tools/qa/skill_manifest.py --check    exit 2 if the committed manifest no longer matches the skill files (a skill changed without a manifest update)

Per skill: name, version (from the `**Version**` header; every skill must have one), the first line of its description, byte size and a short sha256 of the file.
Cross-model skills are not installed in ChatGPT: it must be given these files (see docs/production/README.md).
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/production"


def scan():
    rows = []
    for f in sorted((ROOT / ".claude/skills").glob("*/SKILL.md")):
        t = f.read_text(encoding="utf-8")
        name = re.search(r"^name:\s*(\S+)", t, flags=re.M).group(1)
        v = re.search(r"\*\*Version\*\*\s+(\d+\.\d+\.\d+)", t)
        d = re.search(r"^description:\s*(.+)$", t, flags=re.M).group(1).strip()
        rows.append({"name": name, "version": v.group(1) if v else None, "path": f.relative_to(ROOT).as_posix(), "bytes": len(t.encode("utf-8")),
                     "sha256_16": hashlib.sha256(t.encode("utf-8")).hexdigest()[:16], "description": d,
                     "legacy_alias": d.startswith("LEGACY ALIAS")})
    return rows


def main():
    rows = scan()
    js = json.dumps({"manifest": "LLF skill versions", "lock": "LLF Canonical Local Workflow & Skills Lock v2.0 (2026-10-24)", "skills": rows}, indent=1, ensure_ascii=False) + "\n"
    md = ["# Skill manifest (generated by tools/qa/skill_manifest.py; do not edit)", "", "| Skill | Version | Path | sha256 (16) | Note |", "|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| `{r['name']}` | {r['version']} | `{r['path']}` | `{r['sha256_16']}` | {'legacy alias; use llf-video-director' if r['legacy_alias'] else ''} |")
    md = "\n".join(md) + "\n"
    if "--check" in sys.argv:
        cur = (OUT / "SKILL_MANIFEST.json").read_text(encoding="utf-8") if (OUT / "SKILL_MANIFEST.json").exists() else ""
        if cur != js:
            print("STALE: docs/production/SKILL_MANIFEST.json does not match the skill files; run tools/qa/skill_manifest.py")
            return 2
        print("manifest current:", len(rows), "skills")
        return 0
    (OUT / "SKILL_MANIFEST.json").write_text(js, encoding="utf-8")
    (OUT / "SKILL_MANIFEST.md").write_text(md, encoding="utf-8")
    print("wrote manifest:", len(rows), "skills;", "missing version:", [r["name"] for r in rows if not r["version"]])
    return 0


if __name__ == "__main__":
    sys.exit(main())
